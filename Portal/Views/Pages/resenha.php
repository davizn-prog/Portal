            fazendo coisas repetitivas como um escravo, tornando essas coisas as mais incriveis e desejadas
            de se obter por serem coisas dificeis de se alcançar. O pior é que você descobre depois de muito
            tempo que o que você alcança não vale o esforço empregado porque voce só deseja tanto as coisas
            por elas serem extremamente dificeis e chatas de conseguir, nao por elas serem boas em si mesmas
            e extremamente satisfatorias de forma permanente. Em muitos casos você só vai ver um numero
