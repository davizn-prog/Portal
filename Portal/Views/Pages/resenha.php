        <p>Esse jogo te expulsa dele constantemente, isso se você for um gamer honesto, e provavelmente
            experiente. Se você tem a intenção de se dedicar a esse jogo vai precisar de quase todo seu
            tempo, além de muita paciencia.
        </p>

        <p>No final das contas esse jogo gira em torno de ficar upando boneco. Existe um sistema cheio de
            burocracias onde todas as mecanicas desse jogo giram em torno de te manter constantemente com a
            sensação frustrante de estar correndo atras de algo, desde as armas, personagnes e por incrivel
            que pareça até a forma com que os mapas são construidos e a experiencia com menus. O grandioso
            sistema de limitações que existe em Genshin Impact que pretende te manter preso ao jogo
            acompanhado da promessa de receber algo que vai estar "logo ali", só mais 2 dias, só mais 1
            semana, só mais X horas, só mais esse esforço e voce vai alcançar o que procura, e essa promessa
            é constante pois é um dos sistemas do jogo, a proposta é que você nunca alcance um ponto
            definitivo porque ele deseja te deixar preso la jogando constantemente, pois novos personagens,
            armas e recursos vão aparecendo constantemente inclusive.
        </p>

        <p>Os sistemas de upgrade dos personagens, por exemplo, so te permitem upar o personagem em dias
            especificos onde so vai se ter uma quantidade X de oportinidades de upar o personagem desejado
            em algum de seus atributos, tendo que deixar para o proximo dia que ele o permitir upar aquele
            personagem de novo, que em alguns casos a oportunidade só vai chegar dias depois. Isso gera o
            fato de que um personagem novo só pode ser utilizavel depois de uma quantidade de tempo quase
            que determinada pelo jogo. Isso tambem faz com que voce acabe trocando o foco para outro
            personagem fazendo que voce fique constantemente focado em algum personagem para evoluir, mas é
            preciso levar em conta que isso pode ser prejudicial no futuro pois os materiais que você usou
            para gastar num personagem mediano poderiam ser uteis para um personagem melhor que você nem
            sabe ainda que está para chegar, tornando esse esforço todo uma possivel perda de tempo, fazendo
            você calcular tudo o que vai fazer e mantendo voce numa extase mental absurda calculando
            numeros, dias, horas, cronogramas de atividades extremamente controladas, tornando voce quase
            que um dependente quimico com esse alto nivel de atividade mental para cumprir os cronogramas do
            jogo e se manter dentro dos sistemas dele, te mantendo sempre ocupado para alcançar aquele nivel
            de jogabilidade e experiencia que você deseja. Isso vai se repetir para cada personagem do jogo,
            com alguma variação no nivel de intensidade entre eles.
        </p>

        <p>A exploração é algo que gera alivio nesse jogo pois é uma experiencia gostosa, recompensadora,
            que torna o jogo mais natural e tranquilo de se jogar de forma gratuita, o que torna o jogo
            muito bom no inicio pois sobram recursos para melhorias, apesar do nivel de criatividade e
            qualidade da produção dos mapas tenha decaido muito desde inazuma até aqui. O conteudo de
            exploração é limitado, em algum momento esses recursos vão acabar novamente e seu jogo vai se
            tornar basicamente um cassino onde sem os recursos que você pega jogando eventos, o jogo fica
            injogavel e não resta o que fazer a não ser pagar pelos recursos na loja para não cair no loop
            de fazer as mesmas coisas repetidamente a exaustão para ter alguma experiencia satisfatoria no
            jogo. Aliás, seria isso satisfatório?
        </p>

